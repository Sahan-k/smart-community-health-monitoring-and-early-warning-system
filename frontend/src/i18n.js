/**
 * Helper to translate dynamic risk levels (e.g. "Low", "Medium", "High", "High Risk Signal")
 */
export function translateRisk(t, risk) {
  if (!risk) return '';
  const r = risk.toString().toLowerCase().trim();
  if (r.includes('high')) return t('risk.highRiskSignal');
  if (r.includes('med')) return t('risk.mediumRisk');
  if (r.includes('low')) return t('risk.lowRisk');
  return risk;
}

/**
 * Helper to translate disease names
 */
export function translateDisease(t, disease) {
  if (!disease) return t('diseases.unknownDisease');
  const d = disease.toString().toLowerCase().trim();
  if (d.includes('dengue')) return t('diseases.dengue');
  if (d.includes('viral') || (d.includes('fever') && !d.includes('typhoid'))) return t('diseases.viralFever');
  if (d.includes('malaria')) return t('diseases.malaria');
  if (d.includes('typhoid')) return t('diseases.typhoid');
  if (d.includes('cholera')) return t('diseases.cholera');
  if (d.includes('chikun')) return t('diseases.chikungunya');
  if (d.includes('gastro') || d.includes('diarrh') || d.includes('stools')) return t('diseases.gastroenteritis');
  if (d.includes('covid')) return t('diseases.covid19');
  if (d.includes('influ') || d.includes('flu')) return t('diseases.influenza');
  if (d.includes('respiratory')) return t('diseases.respiratoryInfection');
  return disease;
}

